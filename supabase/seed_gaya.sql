-- blocks (with their subdivision)
insert into public.locations(level, name, parent_id, subdivision)
select distinct 'block', g.block, d.id, g.subdivision
from g
join public.locations s on s.level = 'state' and s.name = 'Bihar'
join public.locations d on d.parent_id = s.id and d.level = 'district' and d.name = 'Gaya'
on conflict do nothing;

update public.locations b set subdivision = g.subdivision
from (select distinct block, subdivision from g) g, public.locations d
where b.level = 'block' and b.parent_id = d.id and d.name = 'Gaya' and d.level = 'district' and lower(b.name) = lower(g.block);

-- panchayats (with the number of villages on record)
insert into public.locations(level, name, parent_id, expected_villages)
select 'panchayat', g.panchayat, b.id, g.villages
from g
join public.locations d on d.level = 'district' and d.name = 'Gaya'
join public.locations b on b.parent_id = d.id and b.level = 'block' and lower(b.name) = lower(g.block)
on conflict do nothing;

drop table g;
